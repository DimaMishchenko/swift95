    /// The normalized Swift case identifier used to reference the icon.
    ///
    /// This value is suitable for catalogs, search, and source-code snippets.
    /// Use ``rawValue`` only when the original resource name is required.
    ///
    /// ```swift
    /// Icon95.Name.addressBook.identifier // "addressBook"
    /// Icon95.Name.addressBook.rawValue // "Addrbook"
    /// ```
    public var identifier: String {
      String(describing: self)
    }

    /// The artwork renditions bundled for this icon.
    ///
    /// Not every icon has all three semantic sizes. ``Icon95`` automatically
    /// falls back to another rendition while preserving the requested rendered
    /// size.
    ///
    /// ```swift
    /// if Icon95.Name.computer.availableSizes.contains(.large) {
    ///   Icon95(.computer, size: .large)
    /// }
    /// ```
    public var availableSizes: [Size] {
      Size.allCases.filter { Self.filename(for: self, size: $0) != nil }
    }

    struct Resource: Sendable {
      let size: Size
      let filename: String
      let pixelWidth: Int
      let pixelHeight: Int

      var pixelSize: CGSize {
        CGSize(width: pixelWidth, height: pixelHeight)
      }

      init(size: Size, filename: String) {
        let components = filename.split(separator: "_")
        let dimensions = components.last?.split(separator: "x")
        guard
          let dimensions,
          dimensions.count == 2,
          let width = Int(dimensions[0]),
          let height = Int(dimensions[1])
        else {
          preconditionFailure("Invalid icon resource filename: \(filename)")
        }
        self.size = size
        self.filename = filename
        pixelWidth = width
        pixelHeight = height
      }
    }

    func resource(for requestedSize: Size) -> Resource {
      let fallbackOrder: [Size]
      switch requestedSize {
      case .small:
        fallbackOrder = [.small, .standard, .large]
      case .standard:
        fallbackOrder = [.standard, .small, .large]
      case .large:
        fallbackOrder = [.large, .small, .standard]
      }

      for size in fallbackOrder {
        if let filename = Self.filename(for: self, size: size) {
          return Resource(size: size, filename: filename)
        }
      }
      preconditionFailure("Missing resources for \(rawValue)")
    }

    private static func filename(for name: Self, size: Size) -> String? {
      bundledResources["\(name.rawValue)_\(size.rawValue)"]
    }

    private static let bundledResources: [String: String] = {
      let urls = Bundle.module.urls(forResourcesWithExtension: "png", subdirectory: "Icons") ?? []
      return Dictionary(
        uniqueKeysWithValues: urls.map { url in
          let filename = url.deletingPathExtension().lastPathComponent
          let components = filename.split(separator: "_")
          let key = components.dropLast().joined(separator: "_")
          return (key, filename)
        })
    }()
  }
